-- ============================================================
-- books 新增「出版社」與「出版日期」兩欄（書籍詳情頁要顯示）
-- ------------------------------------------------------------
-- 兩欄都允許空值（沒寫 not null）：
--   1. 這次遷移之前加入的書沒有這兩項資料，補不回來
--   2. Google Books 本來就不保證每本書都有出版社／出版日期
--
-- published_date 用 text 而不是 date：
--   Google Books 回傳的格式不固定，可能是 "2019"、"2019-06" 或 "2019-06-01"。
--   date 型別一定要有完整的年月日，只有年份的資料會直接寫入失敗。
--   原樣存成文字，畫面要顯示年份時再取前四碼即可。
-- ============================================================
alter table public.books
  add column publisher      text,
  add column published_date text;
